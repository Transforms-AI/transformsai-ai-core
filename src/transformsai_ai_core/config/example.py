"""
Commented example config, generated from the schema's field descriptions and defaults.

``transformsaicore config example`` prints it; the repo's ``config.example.yaml``
is this output, and a test keeps the two identical. Projects can call
``generate_example(seed=..., trailer=...)`` to produce their own template with
their own values on top of core's documented defaults.
"""

import types
from typing import Any, Union, get_args, get_origin

import yaml
from pydantic import BaseModel
from pydantic_core import PydanticUndefined

from .schema import UNSET_MEANS_DEFAULT, Config
from .validate import _is_model, _tagged, _unwrap

COMMENT_COLUMN = 44

# The values the core example shows on top of the defaults (one of each source/input type
# would be noise: alternatives are listed as comments next to the chosen type).
CORE_SEED: dict[str, Any] = {
    "node": {"sn": "node-0001", "version": "1.0.0"},
    "cameras": {
        "surveillance": {
            "source": {"type": "rtsp", "host": "192.168.1.64", "user": "admin", "password": "CHANGEME"},
            "capture": {"fps": 10, "width": 1280, "height": 720},
            "stream": {"bitrate": "800k", "on_demand": True, "audio": {"input": {"type": "camera"}}},
        },
        "ocr": {"source": {"type": "device", "path": "/dev/video0"}},
    },
    "mediamtx": {"host": "mediamtx.example.com"},
    "api": {"base_url": "https://api.example.com/api/v1/", "endpoints": {"heartbeat": "telemetry/heartbeats/"}},
    "models": {"person-det": {"path": "models/yolo11n.pt"}},
}

CORE_HEADER = """\
# transformsai-ai-core 5.0 example config.
# Generated by `transformsaicore config example`; regenerate instead of editing.
#
# Only a few keys are required: node.sn, each camera's source, api.base_url
# (when api is enabled), mediamtx.host (when a stream is enabled), and one of
# path / download_key / type per model. Everything else shows its default.
#
# Every `settings: {}` belongs to the project: core never inspects it. Any other
# unknown key is reported -- an error under `transformsaicore config validate`
# (strict, the pre-deploy gate), a warning at runtime load (lenient).
#
# Durations take seconds or a unit ("500ms", "3s", "2m", "1h");
# bitrates take "800k", "1.2M" or bits/s.
"""

CORE_TRAILER = """\
# ------------------------------------------------------------------------------
# How a project adds its own settings and validators
# ------------------------------------------------------------------------------
# Project keys go in a `settings` block: the top-level one for project-wide
# data, or the one on the object they belong to (a camera, a stream, a model).
#
# To have the same gate check them, register validators before loading:
#
#     from pydantic import BaseModel, ConfigDict
#     from transformsai_ai_core.config import (
#         load_config, register_secret, register_validator)
#
#     class MeterSettings(BaseModel):
#         model_config = ConfigDict(extra="forbid")   # report typos too
#         read_interval: float = 60.0
#
#     register_validator("settings.meter", MeterSettings)
#     register_validator("cameras.*.settings.flash", check_flash)  # a function
#     register_secret("settings.modbus.password")   # masked + redacted in logs
#
#     config, report = load_config("config.yaml")
#
# A function validator returns None/True, False, a message, an Issue, or a
# list of those (or raises ValueError). Failures are errors in strict mode and
# warnings in lenient mode -- pass required=True to make a lenient load refuse
# the config.
"""


def _scalar(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    text = yaml.safe_dump(value, default_flow_style=True, width=10_000, allow_unicode=True).strip()
    if text.endswith("..."):
        text = text[:-3].strip()
    return text


def _line(indent: int, text: str, comment: str | None) -> str:
    line = " " * indent + text
    if comment:
        line = line.ljust(COMMENT_COLUMN) + "  # " + comment if len(line) < COMMENT_COLUMN else f"{line}  # {comment}"
    return line


def _describe(info) -> str:
    text = (info.description or "").strip()
    return f"REQUIRED. {text}" if info.is_required() else text


def _is_union(annotation: Any) -> bool:
    return get_origin(annotation) in (Union, types.UnionType)


def _inline_example(member: type[BaseModel], discriminator: str) -> str:
    """`{type: device, path: /dev/video0}` -- the tag plus required (or example-carrying) fields."""
    tag = get_args(_unwrap(member.model_fields[discriminator].annotation))[0]
    example = {discriminator: tag}
    fields = [(n, f) for n, f in member.model_fields.items() if n != discriminator]
    required = [(n, f) for n, f in fields if f.is_required()]
    for name, info in required or [(n, f) for n, f in fields if f.examples][:1]:
        example[name] = info.examples[0] if info.examples else ""
    return yaml.safe_dump(example, default_flow_style=True, sort_keys=False, width=10_000).strip()


def _render(model: type[BaseModel], seed: dict, indent: int, full: bool, out: list[str]) -> None:
    for name, info in model.model_fields.items():
        if full or name in seed:
            _render_field(name, info, seed, indent, full, out)


def _render_field(name: str, info, seed: dict, indent: int, full: bool, out: list[str]) -> None:
    seeded = name in seed
    value = seed.get(name)
    annotation = _unwrap(info.annotation)
    comment = _describe(info)
    default = info.get_default(call_default_factory=True)

    # Discriminated union: render the seeded member, list the others
    if isinstance(info.discriminator, str) and _is_union(annotation):
        member = _tagged(annotation, info.discriminator, (value or {}).get(info.discriminator))
        if member is None:
            return
        out.append(_line(indent, f"{name}:", comment))
        _render(member, value, indent + 2, full, out)
        others = [m for m in (_unwrap(a) for a in get_args(annotation)) if m is not member]
        for other in others:
            out.append(" " * (indent + 2) + f"# or: {_inline_example(other, info.discriminator)}")
        return

    # Nested block
    if _is_model(annotation):
        if seeded and isinstance(value, dict):
            out.append(_line(indent, f"{name}:", comment))
            _render(annotation, value, indent + 2, full, out)
        elif isinstance(default, BaseModel):
            out.append(_line(indent, f"{name}:", comment))
            _render(annotation, {}, indent + 2, full, out)
        else:
            out.append(_line(indent, f"{name}: {_scalar(value if seeded else default)}", comment))
        return

    # Map of named blocks (cameras, models, endpoints)
    if get_origin(annotation) is dict and _is_model(_unwrap(get_args(annotation)[1])) and seeded:
        item_model = _unwrap(get_args(annotation)[1])
        if all(isinstance(v, str) for v in value.values()):  # shorthand entries, e.g. endpoints
            out.append(_line(indent, f"{name}:", comment))
            for key, item in value.items():
                out.append(_line(indent + 2, f"{key}: {_scalar(item)}", None))
            return
        out.append(_line(indent, f"{name}:", comment))
        for position, (key, item) in enumerate(value.items()):
            out.append(_line(indent + 2, f"{key}:", None))
            _render(item_model, item, indent + 4, full and position == 0, out)
        return

    # Scalars, lists, free dicts
    if seeded:
        shown = value
    elif default is PydanticUndefined:
        shown = info.examples[0] if info.examples else ""
    else:
        shown = default
    text = f"{name}: {_scalar(shown)}"
    if not seeded and info.json_schema_extra == UNSET_MEANS_DEFAULT:
        example = info.examples[0] if info.examples else ""
        out.append(_line(indent, f"# {name}: {_scalar(example)}".rstrip(), comment))
        return
    out.append(_line(indent, text, comment))


def generate_example(seed: dict | None = None, *, header: str | None = None, trailer: str | None = None) -> str:
    """Commented example YAML: every core key with its default and description, plus `seed` values.

    The first entry of a named map (cameras, models) is shown in full; later
    entries only show their seeded keys.
    """
    out: list[str] = []
    seed = CORE_SEED if seed is None else seed
    header = CORE_HEADER if header is None else header
    trailer = CORE_TRAILER if trailer is None else trailer
    if header:
        out.extend(header.rstrip("\n").splitlines())
        out.append("")
    for name, info in Config.model_fields.items():
        _render_field(name, info, seed, 0, True, out)
        out.append("")
    if trailer:
        out.extend(trailer.rstrip("\n").splitlines())
    return "\n".join(out).rstrip() + "\n"

